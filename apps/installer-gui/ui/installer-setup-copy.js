export function installerSensitivePlaceholder(id, configured, copy) {
  if (configured) return copy.keepConfigured;
  return {
    "database-url": "ecto://postgres:postgres@127.0.0.1:5432/kyuubiki_dev",
    "api-token": copy.apiTokenHint,
    "cluster-api-token": copy.clusterTokenHint,
    "direct-mesh-token": copy.directMeshTokenHint,
  }[id];
}

export function renderInstallerSetupCopy(root, copy, { hasCompletionResult = false } = {}) {
  for (const [attribute, target] of [
    ["data-installer-setup-copy", "textContent"],
    ["data-installer-setup-placeholder", "placeholder"],
    ["data-installer-setup-ready-copy", "textContent"],
  ]) {
    if (attribute === "data-installer-setup-ready-copy" && hasCompletionResult) continue;
    root.querySelectorAll(`[${attribute}]`).forEach((node) => {
      const key = node.getAttribute(attribute);
      if (Object.hasOwn(copy, key) && typeof copy[key] === "string") {
        node[target] = copy[key];
      }
    });
  }
  for (const id of ["database-url", "api-token", "cluster-api-token", "direct-mesh-token"]) {
    const input = root.querySelector(`#${id}`);
    if (input) {
      input.placeholder = installerSensitivePlaceholder(id, input.dataset.configured === "true", copy);
    }
  }
}
